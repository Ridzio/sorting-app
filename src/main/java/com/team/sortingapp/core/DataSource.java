package com.team.sortingapp.core;

/**
 * Контракт источника данных для заполнения коллекции сущностей.
 * Реализации: из файла, случайной генерацией, вводом вручную.
 * Заполнение коллекции должно производиться через Stream API (см. задание).
 *
 * @param <T> тип загружаемых сущностей
 */
public interface DataSource<T extends Sortable> {

    /**
     * Загружает и возвращает коллекцию сущностей.
     * Реализация обязана валидировать данные перед добавлением в коллекцию.
     *
     * @param length желаемое количество элементов (для рандома/ручного ввода)
     * @return заполненная кастомная коллекция
     */
    CustomCollection<T> load(int length);
}
