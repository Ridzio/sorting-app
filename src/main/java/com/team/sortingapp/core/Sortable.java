package com.team.sortingapp.core;

/**
 * Контракт, который обязана реализовать любая доменная сущность,
 * участвующая в сортировке. Реализации Sortable могут быть отсортированы
 * стратегиями из пакета sort по любому из своих полей.
 */
public interface Sortable {

    /**
     * Возвращает значение поля по его индексу для использования
     * в сортировке. Индексация полей — с 0.
     *
     * @param fieldIndex индекс поля (0, 1 или 2)
     * @return значение поля, реализующее Comparable
     */
    Comparable<?> getFieldByIndex(int fieldIndex);

    /**
     * @return количество сортируемых полей у сущности (обычно 3)
     */
    int getFieldCount();
}
